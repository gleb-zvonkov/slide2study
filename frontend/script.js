const typingForm = document.querySelector(".typing-form");
const chatList = document.querySelector(".chat-list");
const deleteChatButton = document.querySelector("#delet-chat-button");
let isResponseGenerating = false;
const BASE_URL = "http://127.0.0.1:5000";

/******************************************
 * load in slides from local csv for testing
 ******************************************/
let localSlides = {};

async function loadLocalSlides() {
  const res = await fetch("sample_slides.csv");
  const csvText = await res.text();
  //console.log("CSV Text:", csvText);

  const parsed = Papa.parse(csvText, {
    header: true,
    skipEmptyLines: true,
  });
  //console.log("Parsed CSV:", parsed);

  parsed.data.forEach((row) => {
    const index = parseInt(row.slide_index);
    const text = row.text;
    localSlides[index] = text;
  });

  //console.log("Local Slides Object:", localSlides[4]);
}
loadLocalSlides();

/******************************************
 * extract text from PDF using pdf.js
 ******************************************/
async function extractPdfText(file) {
  const arrayBuffer = await file.arrayBuffer();
  const pdf = await pdfjsLib.getDocument({ data: arrayBuffer }).promise;

  const numPages = pdf.numPages;
  console.log("PDF pages:", numPages);

  localSlides = {}; // reset

  for (let i = 1; i <= numPages; i++) {
    const page = await pdf.getPage(i);
    const content = await page.getTextContent();

    const strings = content.items.map((item) => item.str);
    const pageText = strings.join(" ");

    console.log(pageText);
    localSlides[i] = pageText;
  }

  console.log("Extracted PDF text:", localSlides);
}

/******************************************
 * FRONTEND STATE MACHINE (UNIFIED OBJECT)
 ******************************************/
const state = {
  currentSlide: 4,
  totalSlides: 26,
  bloomOrder: ["content", "remember", "understand", "apply"],
  bloomIndex: 0,
  freetalk: false,
  currentQuestion: null,
  freeTalkHistory: [],
};

